//! 文末 (句点・読点・感嘆符・行末の直前) を古語の形にする。

use std::sync::LazyLock;

use regex::Regex;

/// 文末の区切り (句読点・感嘆符・閉じ括弧・行末)
const END: &str = r"(?P<e>[。、！？!?」』]|$)";

/// 五段動詞の意志形 (お段＋う) → 古語の推量 (あ段＋ん)
const GODAN_VOLITIONAL: &[(&str, &str)] = &[
    ("こ", "か"),
    ("そ", "さ"),
    ("と", "た"),
    ("の", "な"),
    ("も", "ま"),
    ("ろ", "ら"),
    ("ご", "が"),
    ("ぼ", "ば"),
    ("お", "わ"),
];

/// (正規表現の本体, 置き換え)。本体の後ろに END を付けて使う。上から順に当てはめる。
const RULES: &[(&str, &str)] = &[
    ("なかった", "ざりき"),
    ("しない", "せず"),
    // 動詞の否定 (未然形＋ない)。「お金がない」「時間はない」「少ない」は対象外
    (
        "([かさたまらわきけしせちてにねひへみめりれびべぎげじぜいえ])ない",
        "${1}ず",
    ),
    ("だろう", "ならん"),
    ("でしょう", "ならん"),
    ("しよう", "せん"),
    // 一段動詞の意志形
    ("([べめけせてねれげぜえみきちにりびぎじい])よう", "${1}ん"),
];

/// RULES と五段の意志形の後に当てはめる規則
const LATE_RULES: &[(&str, &str)] = &[
    ("ている", "ておる"),
    ("でいる", "でおる"),
    ("たい", "たし"),
    ("でした", "なりき"),
    ("です", "なり"),
    ("ました", "けり"),
    ("ません", "ませぬ"),
    ("ます", "候"),
    ("だった", "なりき"),
    // 「飲んだ」「泳いだ」 (過去形) は対象外
    (r"([^んい\n])だ", "${1}なり"),
    ("かった", "かりけり"),
    // 形容詞 (漢字＋い / 漢字＋しい)。ひらがなだけの「きれい」等は対象外
    (r"(\p{Han})(し)?い", "${1}し"),
    ("た", "たり"),
];

static COMPILED: LazyLock<Vec<(Regex, String)>> = LazyLock::new(|| {
    let godan = GODAN_VOLITIONAL
        .iter()
        .map(|(o, a)| (format!("{o}う"), format!("{a}ん")));
    RULES
        .iter()
        .map(|(p, r)| (p.to_string(), r.to_string()))
        .chain(godan)
        .chain(
            LATE_RULES
                .iter()
                .map(|(p, r)| (p.to_string(), r.to_string())),
        )
        .map(|(p, r)| {
            (
                Regex::new(&format!("(?m){p}{END}")).unwrap(),
                format!("{r}${{e}}"),
            )
        })
        .collect()
});

/// 文末の規則を順に当てはめる。
pub fn apply(text: &str) -> String {
    COMPILED.iter().fold(text.to_owned(), |acc, (re, rep)| {
        re.replace_all(&acc, rep.as_str()).into_owned()
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    // K3
    #[test]
    fn k3_endings_table() {
        for (from, to) in [
            ("行かなかった。", "行かざりき。"),
            ("行かない。", "行かず。"),
            ("食べない。", "食べず。"),
            ("しない。", "せず。"),
            ("飲もう。", "飲まん。"),
            ("行こう。", "行かん。"),
            ("買おう。", "買わん。"),
            ("しよう。", "せん。"),
            ("食べよう。", "食べん。"),
            ("だろう。", "ならん。"),
            ("でしょう。", "ならん。"),
            ("寝ている。", "寝ておる。"),
            ("読んでいる。", "読んでおる。"),
            ("帰りたい。", "帰りたし。"),
            ("学生です。", "学生なり。"),
            ("学生でした。", "学生なりき。"),
            ("行きます。", "行き候。"),
            ("行きました。", "行きけり。"),
            ("行きません。", "行きませぬ。"),
            ("雨だった。", "雨なりき。"),
            ("雨だ。", "雨なり。"),
            ("楽しかった。", "楽しかりけり。"),
            ("寒い。", "寒し。"),
            ("美しい。", "美し。"),
            ("食べた。", "食べたり。"),
        ] {
            assert_eq!(apply(from), to, "{from}");
        }
    }

    #[test]
    fn k3_leaves_risky_forms_alone() {
        for s in [
            "お金がない。",
            "時間はない。",
            "少ない。",
            "きれい。",
            "大きい。",
            "飲んだ。",
            "泳いだ。",
            "行くよ。",
        ] {
            assert_eq!(apply(s), s, "{s}");
        }
    }

    #[test]
    fn k3_applies_at_clause_and_line_ends() {
        assert_eq!(apply("行かない、寒い"), "行かず、寒し");
        assert_eq!(apply("寒い\n楽しかった"), "寒し\n楽しかりけり");
        assert_eq!(apply("行かないで"), "行かないで");
    }
}
